class MetadataTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        self.calibration = self.root / "calibration"
        (self.calibration / "tf").mkdir(parents=True)
        (self.calibration / "tf/calibration_latest.yaml").write_text(yaml.safe_dump({"calibration_metadata": {
            "camera": "2025-01-02-03-04-05", "prism": "2025-02-02-03-04-05", "imu": "cad"}}))
        for folder, names in export.EXPECTED_FILES.items():
            (self.calibration / folder).mkdir()
            for name in names:
                (self.calibration / folder / name).write_text(yaml.safe_dump({"rostopic": f"/{folder}/{name}"}))
        self.tf = TFMessage(transforms=[TransformStamped()])
        self.output = self.root / "latest.bag"
        self.output.write_bytes(b"prior calibration")

    def test_complete_bag_dates_and_topics(self):
        output, dated = export.write_calibration_bags(self.output, self.tf, self.calibration,
                                                     "2024-01-01-00-00-00", "2026-01-01-00-00-00")
        self.assertEqual(output.read_bytes(), dated.read_bytes())
        with rosbag.Bag(str(output)) as bag:
            records = list(bag.read_messages())
        self.assertEqual(len(records), 12)
        metadata = yaml.safe_load(next(msg.data for topic, msg, _ in records if topic == "/calibration_metadata"))
        self.assertEqual(metadata["validity_start"], "2024-01-01-00-00-00")
        self.assertEqual(metadata["validity_end"], "2026-01-01-00-00-00")
        self.assertIn("2024-01-01-00-00-00__2026-01-01-00-00-00", dated.name)
        prior = output.read_bytes()
        with self.assertRaises(FileExistsError):
            export.write_calibration_bags(output, self.tf, self.calibration,
                                         "2024-01-01-00-00-00", "2026-01-01-00-00-00")
        self.assertEqual(output.read_bytes(), prior)

    def test_default_start_preserved(self):
        summary, _ = export.load_calibration_records(self.calibration, validity_end="2026-01-01-00-00-00")
        self.assertEqual(summary["validity_start"], "2025-01-02-03-04-05")

    def test_bad_dates_and_missing_camera_preserve_output(self):
        for start, end in [("bad", ""), ("2026-02-01-00-00-00", "2026-01-01-00-00-00")]:
            with self.assertRaises(ValueError):
                export.write_calibration_bags(self.output, self.tf, self.calibration, start, end)
        (self.calibration / "alphasense/cam1.yaml").unlink()
        with self.assertRaises(FileNotFoundError):
            export.write_calibration_bags(self.output, self.tf, self.calibration)
        self.assertEqual(self.output.read_bytes(), b"prior calibration")
        self.assertEqual(list(self.root.glob("*.bag")), [self.output])

    def test_empty_tf_and_failed_publication_leave_no_partial_bag(self):
        with self.assertRaises(ValueError):
            export.write_calibration_bags(self.output, TFMessage(), self.calibration)
        with patch.object(export.os, "replace", side_effect=OSError("disk error")):
            with self.assertRaises(OSError):
                export.write_calibration_bags(self.output, self.tf, self.calibration)
        self.assertEqual(self.output.read_bytes(), b"prior calibration")
        self.assertFalse(list(self.root.glob(".*.bag")))
        self.assertFalse(list(self.root.glob("tf_static_metadata*")))


class BatchTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        self.inputs = self.root / "raw"
        self.inputs.mkdir()
        self.path = self.inputs / "data.bag"
        # Reuse a real ROS detection type generated by the calibration package.
        from grand_tour_camera_detection_msgs.msg import CameraDetections
        with rosbag.Bag(str(self.path), "w") as bag:
            imu = Imu()
            imu.header.stamp = rospy.Time(10)
            bag.write("/gt_box/stim320/imu", imu, rospy.Time(11))
            bag.write("/camera_corner_detections", CameraDetections(), rospy.Time(11))
        self.original = self.path.read_bytes()
        self.calibration = self.root / "camera.yaml"
        self.calibration.write_text("{}")
        self.output = self.root / "imu.yaml"
        self.output.write_text("previous result")
        self.allan = PACKAGE / "calibration/allan_variances"

    def run_batch(self, **kwargs):
        with contextlib.redirect_stdout(io.StringIO()):
            return run_camera_imu_batch(self.inputs, self.calibration, self.output, self.allan, **kwargs)

    def test_commands_timestamp_preservation_and_cleanup(self):
        calls = []
        def runner(command):
            calls.append(command)
            self.assertEqual(command[2], "camera_imu_offline_calibration")
            self.assertIn("--camera_detection_bags", command)
            self.assertNotIn("--camera_bags", command)
            with rosbag.Bag(command[command.index("-b") + 1]) as bag:
                _, message, stamp = next(bag.read_messages())
            self.assertEqual(message.header.stamp, rospy.Time(10))
            self.assertEqual(stamp, rospy.Time(11))
            Path(command[command.index("-o") + 1]).write_text(yaml.safe_dump({"/gt_box/stim320/imu": {
                "T_camerabundle_imu": np.eye(4).tolist(), "biases": {"10": {"gyro": [0, 0, 0]}}}}))
        self.run_batch(runner=runner)
        self.assertEqual(len(calls), 1)
        result = yaml.safe_load(self.output.read_text())
        self.assertIn("stim320_imu", result)
        self.assertIn("biases", result["stim320_imu"])
        self.assertEqual(self.path.read_bytes(), self.original)
        self.assertFalse(list(self.root.glob(".camera-imu-*")))

    def test_failure_preserves_old_output_and_inputs(self):
        def failed(command):
            raise subprocess.CalledProcessError(1, command)
        with self.assertRaises(subprocess.CalledProcessError):
            self.run_batch(runner=failed)
        self.assertEqual(self.output.read_text(), "previous result")
        self.assertEqual(self.path.read_bytes(), self.original)
        self.assertFalse(list(self.root.glob(".camera-imu-*")))

    def test_dry_run_writes_nothing_and_runs_nothing(self):
        before = sorted(str(p) for p in self.root.rglob("*"))
        with patch("subprocess.run", side_effect=AssertionError("Must not execute")):
            self.run_batch(dry_run=True)
        self.assertEqual(before, sorted(str(p) for p in self.root.rglob("*")))
        self.assertEqual(self.output.read_text(), "previous result")

    def test_explicit_topic_requires_correct_type(self):
        with self.assertRaises(ValueError):
            select_imus({"/corrected": "ap20_driver_ros/ImuDebug"}, self.allan, {"ap20": "/corrected"})
        selected = select_imus({"/corrected": "sensor_msgs/Imu"}, self.allan, {"ap20": "/corrected"})
        self.assertEqual(selected, {"/corrected": "ap20_imu"})

    def test_invalid_transform_rejected(self):
        for value in [np.zeros((4, 4)), np.full((4, 4), np.nan), np.diag([-1, 1, 1, 1])]:
            with self.assertRaises(ValueError):
                validate_transform(value)

    def test_full_workflow_dry_run_creates_no_outputs(self):
        command = [sys.executable, str(PACKAGE / "scripts/process_all_calibrations.py"),
                   "-cc", str(self.inputs), "-cl", str(self.inputs), "-cp", str(self.inputs),
                   "-ci", str(self.inputs), "--output-dir", str(self.root / "results"), "--dry_run"]
        env = os.environ.copy()
        env["ROS_PACKAGE_PATH"] = str(PACKAGE.parent) + ":" + env.get("ROS_PACKAGE_PATH", "")
        result = subprocess.run(command, cwd=self.root, capture_output=True, text=True, env=env)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertFalse((self.root / "results").exists())
        self.assertEqual(self.path.read_bytes(), self.original)


class FullWorkflowTests(unittest.TestCase):
    def test_staged_exports_and_imu_graph_wiring(self):
        # Mock only external calibration programs. Exercise the orchestration,
        # actual graph converter and generated camera/metadata consumer formats.
        import process_all_calibrations as workflow
        from sensor_msgs.msg import Image
        from geometry_msgs.msg import PointStamped
        topics = [f"/gt_box/alphasense_driver_node/cam{i}" for i in range(1, 6)]
        topics += [f"/gt_box/hdr_{side}/image_raw" for side in ("front", "left", "right")]
        topics += [f"/gt_box/zed2i_driver_node/{side}_raw/image_raw_color" for side in ("left", "right")]
        cameras = {f"cam{i}": {"rostopic": topic, "T_bundle_camera": np.eye(4).tolist(),
                   "resolution": [1280, 960], "intrinsics": [600, 610, 640, 480],
                   "distortion_coeffs": [0, 0, 0, 0], "distortion_model": "radtan"}
                   for i, topic in enumerate(topics)}
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            inputs = root / "inputs"
            inputs.mkdir()
            source = inputs / "calibration.bag"
            with rosbag.Bag(str(source), "w") as bag:
                bag.write(topics[0], Image(), rospy.Time(1700000000))
                bag.write("/gt_box/ap20/position_debug", PointStamped(), rospy.Time(1700000000))
            original = source.read_bytes()
            calls = []
            def run(command):
                calls.append(command)
                executable = command[2]
                if executable == "camera_camera_offline_calibration":
                    Path(command[-1]).write_text("#2023-11-14-23-13-20\n" + yaml.safe_dump(cameras))
                elif executable == "convert_ceres_camera_output_to_kalibr_style.py":
                    Path(command[4]).write_text(yaml.safe_dump(cameras))
                elif executable == "offline_calibrator.py":
                    settings = yaml.safe_load(Path(command[-1]).read_text())
                    alignment = Path(settings["logging_dir"]) / "04_alignment"
                    alignment.mkdir(parents=True)
                    np.savetxt(alignment / "reprojection_errors.txt", [[0, 0], [0.001, -0.001]])
                    np.savetxt(alignment / "homography-merged-cloud.txt", [[0, 0, 0, 1], [1, 1, 0, 2]])
                    (alignment / "diffcal-calib.yaml").write_text(yaml.safe_dump({"cam0": {"T_cam_lidar": np.eye(4).tolist()}}))
                elif executable == "camera_imu_preprocess":
                    from grand_tour_camera_detection_msgs.msg import CameraDetections
                    with rosbag.Bag(command[command.index("--output")+1], "w") as bag:
                        bag.write(topics[0] + "_corner_detections", CameraDetections(), rospy.Time(1700000000))
                elif executable == "camera_prism_offline_calibration":
                    data = yaml.safe_load(Path(command[command.index("-c")+1]).read_text())
                    for camera in data.values():
                        camera["t_cam_prism"] = [0.1, 0.2, 0.3]
                    Path(command[command.index("-o")+1]).write_text(yaml.safe_dump(data))
                elif executable == "convert_graph.py":
                    self.assertIn("-imu", command)
                    subprocess.run([sys.executable, str(PACKAGE / "scripts/convert_graph.py"), *command[3:]],
                                   check=True, capture_output=True)
                else:
                    self.fail(f"Unexpected command: {command}")
            def imu(folder, calibration, output, allan, overrides):
                self.assertEqual(folder, str(inputs))
                self.assertTrue(Path(calibration).is_file())
                Path(output).write_text(yaml.safe_dump({"stim320_imu": {"T_camerabundle_imu": np.eye(4).tolist()}}))
                return "2023-11-14-23-13-20"
            argv = ["process_all_calibrations.py", "-cc", str(inputs), "-cl", str(inputs), "-cp", str(inputs),
                    "-ci", str(inputs), "--output-dir", str(root / "results")]
            cwd = Path.cwd()
            try:
                with patch.object(sys, "argv", argv), patch.object(workflow.rospack, "get_path", return_value=str(PACKAGE)), \
                        patch.object(workflow, "safe_subprocess_run", side_effect=run), \
                        patch.object(workflow, "run_camera_imu_batch", side_effect=imu), contextlib.redirect_stdout(io.StringIO()):
                    workflow.main()
            finally:
                os.chdir(cwd)
            deployment = root / "results/deployment"
            metadata, records = export.load_calibration_records(deployment, validity_end="2026-01-01-00-00-00")
            self.assertEqual(len(records), 11)
            self.assertEqual(metadata["imu"], "2023-11-14-23-13-20")
            self.assertEqual(source.read_bytes(), original)
            self.assertEqual(list(inputs.iterdir()), [source])



