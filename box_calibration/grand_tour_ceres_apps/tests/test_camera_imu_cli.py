#!/usr/bin/env python3
"""End-to-end synthetic camera–IMU calibration, output and Rerun regression.

Run in a sourced ROS workspace:
  python3 test_camera_imu_cli.py --executable /path/to/camera_imu_offline_calibration
No raw recording is required. All generated files are removed on completion.
"""

import argparse
import json
import os
import shutil
import subprocess
import tempfile
from pathlib import Path

import numpy as np
import rosbag
import rospy
import yaml
from geometry_msgs.msg import Point
from sensor_msgs.msg import Imu
from scipy.spatial.transform import Rotation
from grand_tour_camera_detection_msgs.msg import CameraDetections


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--executable", required=True, type=Path)
    args = parser.parse_args()
    executable = args.executable.resolve()
    work = Path(tempfile.mkdtemp(prefix="grand_tour_imu_cli_test_"))
    env = os.environ.copy()
    env["ROS_HOME"] = str(work / "ros")
    env["OPENBLAS_NUM_THREADS"] = "1"
    results = {}

    def run(name, command):
        result = subprocess.run(
            [str(executable), *map(str, command[1:])], capture_output=True, text=True, env=env, timeout=240
        )
        results[name] = {"exit_code": result.returncode}
        if result.returncode:
            print(result.stdout)
            print(result.stderr)
        return result.returncode

    try:
        # Independent synthetic measurements generated by piecewise-constant IMU motion.
        expected = np.eye(4)
        expected[:3, :3] = Rotation.from_rotvec([0.1, -0.07, 0.08]).as_matrix()
        expected[:3, 3] = [0.04, -0.02, 0.03]
        camera = {
            "cam0": {
                "rostopic": "/camera0",
                "intrinsics": [600.0, 610.0, 640.0, 480.0],
                "distortion_model": "radtan",
                "distortion_coeffs": [0.0, 0.0, 0.0, 0.0],
                "resolution": [1280, 960],
                "T_bundle_camera": np.eye(4).tolist(),
            }
        }
        (work / "cameras.yaml").write_text(yaml.safe_dump(camera))
        position = np.array([0.0, 0.0, -2.0])
        velocity = np.zeros(3)
        orientation = np.eye(3)
        gravity = np.array([0.0, 0.0, -9.81])
        dt = 0.01
        points = np.array([[(x - 4.5) * 0.045, (y - 4.5) * 0.045, 0] for y in range(10) for x in range(10)])
        with rosbag.Bag(str(work / "imu.bag"), "w") as imu_bag, rosbag.Bag(str(work / "camera.bag"), "w") as cameras:
            for step in range(801):
                t = step * dt
                stamp = rospy.Time.from_sec(10 + t)
                gyro = np.array([0.35 * np.sin(t * 1.7), 0.3 * np.cos(t * 1.3), 0.2 * np.sin(t * 2.1)])
                acceleration = np.array([0.4 * np.cos(t * 2), 0.3 * np.cos(t * 2.4), 0.25 * np.cos(t * 1.9)])
                specific = orientation.T @ (acceleration - gravity)
                imu = Imu()
                imu.header.stamp = stamp
                imu.header.frame_id = "imu"
                imu.angular_velocity.x, imu.angular_velocity.y, imu.angular_velocity.z = gyro
                imu.linear_acceleration.x, imu.linear_acceleration.y, imu.linear_acceleration.z = specific
                imu_bag.write("/imu", imu, stamp)
                if step % 10 == 0:
                    T = np.eye(4)
                    T[:3, :3] = orientation
                    T[:3, 3] = position
                    T_camera_board = expected @ np.linalg.inv(T)
                    xyz = points @ T_camera_board[:3, :3].T + T_camera_board[:3, 3]
                    msg = CameraDetections()
                    msg.header.stamp = stamp
                    msg.header.frame_id = "camera0"
                    msg.cornerids = list(range(len(points)))
                    msg.modelpoint3d = [Point(*p) for p in points]
                    msg.corners2d = [Point(600 * p[0] / p[2] + 640, 610 * p[1] / p[2] + 480, 0) for p in xyz]
                    cameras.write("/camera0_corner_detections", msg, stamp)
                position = position + velocity * dt + 0.5 * acceleration * dt * dt
                velocity += acceleration * dt
                orientation = orientation @ Rotation.from_rotvec(gyro * dt).as_matrix()
        args = [
            "camera_imu_offline_calibration",
            "-c",
            work / "cameras.yaml",
            "--camera_detection_bags",
            work / "camera.bag",
            "-b",
            work / "imu.bag",
            "-t",
            "/imu",
            "-o",
            work / "imu_calibration.yaml",
            "--rerun_recording",
            work / "imu.rrd",
        ]
        code = run("imu_synthetic_solver", args)
        if code == 0:
            result = yaml.safe_load((work / "imu_calibration.yaml").read_text())["/imu"]
            actual = np.asarray(result["T_camerabundle_imu"])
            assert np.isfinite(actual).all()
            results["imu_synthetic_solver"].update(
                {
                    "rotation_error_radians": float(
                        Rotation.from_matrix(expected[:3, :3].T @ actual[:3, :3]).magnitude()
                    ),
                    "translation_error_meters": float(np.linalg.norm(expected[:3, 3] - actual[:3, 3])),
                    "bias_keyframes": len(result["biases"]),
                    "rrd_bytes": (work / "imu.rrd").stat().st_size,
                }
            )
        else:
            raise AssertionError("Synthetic calibration did not converge")
        from box_calibration.camera_imu_batch import run_camera_imu_batch
        import rospkg
        allan = Path(rospkg.RosPack().get_path("box_calibration")) / "calibration/allan_variances"
        def batch_runner(command):
            subprocess.run([str(executable), *command[3:]], env=env, check=True,
                           capture_output=True, text=True, timeout=240)
        run_camera_imu_batch(work, work / "cameras.yaml", work / "batch.yaml", allan,
                             {"stim320": "/imu"}, runner=batch_runner)
        aggregate = yaml.safe_load((work / "batch.yaml").read_text())
        np.testing.assert_allclose(aggregate["stim320_imu"]["T_camerabundle_imu"], expected, atol=1e-4)
        assert not list(work.glob(".camera-imu-*"))
        results["imu_batch_solver"] = {"passed": True, "temporary_bags_removed": True}
        assert run("imu_unsupported_time_offset", args + ["--solve_time_offset"]) != 0
        assert results["imu_synthetic_solver"]["rotation_error_radians"] < 1e-4
        assert results["imu_synthetic_solver"]["translation_error_meters"] < 1e-4
        assert results["imu_synthetic_solver"]["bias_keyframes"] == 81
        assert results["imu_synthetic_solver"]["rrd_bytes"] > 100
    finally:
        shutil.rmtree(work)
        results["temporary_outputs_removed"] = not work.exists()
        print(json.dumps(results, indent=2))


if __name__ == "__main__":
    main()
